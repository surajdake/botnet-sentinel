import { useCallback, useEffect, useState } from "react";
import { AlertTriangle, CheckCircle, Clock, RefreshCw, ShieldAlert } from "lucide-react";
import { api } from "./api";

function ResponseCenter({ deviceId = null }) {
  const [actions, setActions] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const loadActions = useCallback(async () => {
    try {
      setLoading(true);
      setError("");

      const data = deviceId
        ? await api.getDeviceResponses(deviceId)
        : await api.getResponseActions();

      setActions(Array.isArray(data) ? data : []);
    } catch (err) {
      console.error("Response Center error:", err);
      setError(err.message || "Unable to load response actions");
    } finally {
      setLoading(false);
    }
  }, [deviceId]);

  useEffect(() => {
    loadActions();
  }, [loadActions]);

  const handleStatusChange = async (id, status) => {
    try {
      await api.updateResponseStatus(id, status);
      await loadActions();
    } catch (err) {
      setError(err.message || "Unable to update response status");
    }
  };

  const getPriorityClass = (priority) => {
    switch (priority) {
      case "CRITICAL":
        return "critical";
      case "HIGH":
        return "high";
      case "MEDIUM":
        return "medium";
      default:
        return "low";
    }
  };

  

const getStatusIcon = (status) => {
  switch (status) {
    case "EXECUTED":
      return <CheckCircle size={16} />;

    case "SIMULATED":
      return <ShieldAlert size={16} />;

    case "FAILED":
      return <AlertTriangle size={16} />;

    case "PENDING":
      return <Clock size={16} />;

    case "CANCELLED":
      return <AlertTriangle size={16} />;

    default:
      return <ShieldAlert size={16} />;
  }
};


const getStatusLabel = (status) => {
  switch (String(status || "").toUpperCase()) {
    case "SIMULATED":
      return "Simulated — not applied to device";
    case "EXECUTED":
      return "Executed";
    case "PENDING":
      return "Pending";
    case "FAILED":
      return "Failed";
    case "CANCELLED":
      return "Cancelled";
    default:
      return "Unknown";
  }
};


  const formatDate = (date) => {
    if (!date) return "Unknown";

    return new Date(date).toLocaleString();
  };

  return (
    <div className="response-center">

      {/* HEADER */}
      <div className="response-header">
        <div>
          <div className="response-eyebrow">
            AUTOMATED DEFENSE
          </div>

          <h1>Response Center</h1>

          <p>
            Security response actions generated by the mobile botnet
            detection engine.
          </p>
        </div>

        <button
          className="response-refresh"
          onClick={loadActions}
          disabled={loading}
        >
          <RefreshCw size={16} />
          Refresh
        </button>
      </div>


      {/* ERROR */}
      {error && (
        <div className="response-error">
          <AlertTriangle size={18} />
          <span>{error}</span>
        </div>
      )}


      {/* LOADING */}
      {loading && (
        <div className="response-empty">
          Loading response actions...
        </div>
      )}


      {/* NO DATA */}
      {!loading && !error && actions.length === 0 && (
        <div className="response-empty">
          <ShieldAlert size={32} />

          <h3>No response actions</h3>

          <p>
            The detection engine has not generated any response actions yet.
          </p>
        </div>
      )}


      {/* RESPONSE ACTIONS */}
      {!loading && actions.length > 0 && (
        <div className="response-list">

          {actions.map((item) => (
            <div
              className="response-card"
              key={item.id}
            >

              <div className="response-card-top">

                <div className="response-action-icon">
                  <ShieldAlert size={21} />
                </div>

                <div className="response-action-info">

                  <h2>
                    {item.action || "UNKNOWN_ACTION"}
                  </h2>

                  <span>
                    Response #{item.id}
                  </span>

                </div>

                <div
                  className={`priority-badge ${getPriorityClass(
                    item.priority
                  )}`}
                >
                  {item.priority || "LOW"}
                </div>

              </div>


              {/* DEVICE */}
              <div className="response-device">

                <div>
                  <span className="response-label">
                    DEVICE
                  </span>

                  <strong>
                    {item.device_name || `Device ${item.device_id}`}
                  </strong>
                </div>

                <div>
                  <span className="response-label">
                    IP ADDRESS
                  </span>

                  <strong>
                    {item.ip_address || "Unknown"}
                  </strong>
                </div>

                <div>
                  <span className="response-label">
                    RISK
                  </span>

                  <strong>
                    {item.risk_score ?? 0}/100
                  </strong>
                </div>
              </div>


              {/* REASON */}
              <div className="response-reason">

                <span className="response-label">
                  RESPONSE REASON
                </span>

                <p>
                  {item.reason || "No reason provided."}
                </p>

              </div>


              {/* FOOTER */}
              <div className="response-card-footer">

                <div className="response-status">

                  {getStatusIcon(item.status)}

                 <span>
  {getStatusLabel(item.status)}
</span>
                </div>

                <span className="response-date">
                  {formatDate(item.created_at)}
                </span>


                {/* ACTION BUTTONS */}
                
{String(item.status || "").toUpperCase() === "PENDING" && (
  <div className="response-buttons">
    <button
      onClick={() => handleStatusChange(item.id, "SIMULATED")}
    >
      Mark Simulated
    </button>

    <button
      className="secondary"
      onClick={() => handleStatusChange(item.id, "CANCELLED")}
    >
      Cancel
    </button>
  </div>
)}


              </div>

            </div>
          ))}

        </div>
      )}

    </div>
  );
}

export default ResponseCenter;